export function modificationFor(e: Exercise): string {
  if (BY_ID[e.id]) return BY_ID[e.id];
  if (BY_PATTERN[e.movementPattern]) return BY_PATTERN[e.movementPattern];
  if (e.movementPattern.startsWith('core')) return 'Acorta la palanca: rodillas dobladas o apoyadas, y menos tiempo.';
  return 'Hazlo más lento, con menos peso o menos rango, sin dolor.';
}
